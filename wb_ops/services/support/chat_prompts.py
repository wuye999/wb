def recent_turns(events: List[Dict[str, Any]], max_turns: int = 3) -> List[str]:
    """取最近若干轮对话（排除最新一条），整理为「买家：…」/「卖家：…」行，旧→新。

    Args:
        events: 消息历史事件（倒序，[0] 最新）。
        max_turns: 最多取多少轮（1 轮≈1 条消息），实际取条数 = 2*max_turns 后再截断。

    Returns:
        对话行列表（旧→新），空消息已跳过。
    """
    if not events or max_turns <= 0:
        return []
    older = events[1: 1 + 2 * max_turns]           # 排除最新一条
    lines: List[str] = []
    for ev in reversed(older):                      # 反转为旧→新
        if not isinstance(ev, dict):
            continue
        text = ((ev.get("message") or {}).get("text") or "").strip()
        if not text:
            continue
        who = "卖家" if ev.get("isOwn") else "买家"
        lines.append(f"{who}：{text}")
    return lines


def build_user_prompt(product_info: str, buyer_message: str,
                      recent: List[str] = None) -> str:
    """组装 user prompt：商品信息 + 近期对话（可选）+ 待回复的最新买家消息。"""
    parts = ["【商品信息】", product_info or "(无商品信息)"]
    if recent:
        parts += ["", "【近期对话（从旧到新，仅供理解上下文）】", *recent]
    parts += ["", "【需要你回复的买家最新消息】", buyer_message or ""]
    return "\n".join(parts)
